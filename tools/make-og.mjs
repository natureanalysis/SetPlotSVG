const ACCENT = [59, 130, 246];

function render({ brand, sub, footer }) {
  const buf = Buffer.alloc(W * H * 3);
  const px = (x, y, r, g, b) => {
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    const i = (y * W + x) * 3;
    buf[i] = r; buf[i + 1] = g; buf[i + 2] = b;
  };
  const rect = (x0, y0, w, h, r, g, b) => {
    for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) px(x, y, r, g, b);
  };
  const text = (s, x, y, sc, r, g, b) => {
    let cx = x;
    for (const ch of String(s).toUpperCase()) {
      const gl = F[ch] || F[" "];
      for (let ry = 0; ry < 7; ry++) for (let rx = 0; rx < 5; rx++) {
        if (gl[ry][rx] === "1") rect(cx + rx * sc, y + ry * sc, sc, sc, r, g, b);
      }
      cx += 6 * sc;
    }
  };
  for (let y = 0; y < H; y++) {
    const t = y / (H - 1);
    for (let x = 0; x < W; x++) {
      const d = Math.hypot(x / (W - 1) - 0.3, t - 0.35) * 0.9;
      const k = Math.max(0, 0.55 - d) + 0.16 * (1 - t);
      px(x, y, Math.round(6 + ACCENT[0] * 0.18 * k),
             Math.round(10 + ACCENT[1] * 0.18 * k),
             Math.round(23 + ACCENT[2] * 0.18 * k));
    }
  }
  rect(0, 0, W, 8, ACCENT[0], ACCENT[1], ACCENT[2]);
  text(brand, 90, 150, 9, 255, 255, 255);
  rect(90, 245, 150, 5, ACCENT[0], ACCENT[1], ACCENT[2]);
  text(sub, 90, 300, 4, 175, 190, 215);
  rect(0, H - 76, W, 76, 8, 14, 30);
  text(footer, 90, H - 52, 4, 120, 145, 195);
  return buf;
}

const crcTable = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();
const crc32 = b => {
  let c = -1;
  for (const x of b) c = crcTable[(c ^ x) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
};
/* 8 位真彩色（color type 2）、逐行 filter 0、deflate */
function encodePng(buf) {
  const stride = W * 3 + 1;
  const raw = Buffer.alloc(H * stride);
  for (let y = 0; y < H; y++) {
    raw[y * stride] = 0;
    buf.copy(raw, y * stride + 1, y * W * 3, (y + 1) * W * 3);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4);
  ihdr[8] = 8; ihdr[9] = 2;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0))
  ]);
}

